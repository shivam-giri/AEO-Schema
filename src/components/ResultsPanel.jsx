import { Download, RefreshCw, Link, Tag } from 'lucide-react';
import AEOScoreCard from './AEOScoreCard.jsx';
import SchemaCard from './SchemaCard.jsx';

const PAGE_TYPE_LABELS = {
  article: { label: 'Article / Blog', emoji: '📝' },
  faq:     { label: 'FAQ Page',       emoji: '❓' },
  howto:   { label: 'How-To Guide',   emoji: '🪜' },
  homepage:{ label: 'Homepage',       emoji: '🏠' },
  product: { label: 'Product Page',   emoji: '📦' },
  generic: { label: 'Generic Page',   emoji: '🌐' },
};

export default function ResultsPanel({ results, onReset }) {
  const { schemas, score, meta, pageType } = results;
  const pageTypeInfo = PAGE_TYPE_LABELS[pageType] || PAGE_TYPE_LABELS.generic;

  const handleDownloadAll = () => {
    const allSchemas = schemas.map(s => s.schema);
    const blob = new Blob(
      [JSON.stringify(allSchemas, null, 2)],
      { type: 'application/json' }
    );
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'aeo-schemas.json';
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadHTML = () => {
    const scriptTags = schemas
      .map(s => `<script type="application/ld+json">\n${JSON.stringify(s.schema, null, 2)}\n</script>`)
      .join('\n\n');

    const html = `<!-- AEO Schema Markup generated by AEO Schema Generator -->\n<!-- Add these tags to your <head> section -->\n\n${scriptTags}`;
    const blob = new Blob([html], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'aeo-schemas.html';
    a.click();
    URL.revokeObjectURL(url);
  };

  const shortUrl = (() => {
    try {
      const u = new URL(meta.canonicalUrl || '');
      return u.hostname + (u.pathname !== '/' ? u.pathname : '');
    } catch { return meta.canonicalUrl; }
  })();

  return (
    <section className="results-section" aria-label="AEO Analysis Results">
      {/* Results header */}
      <div className="results-header">
        <div>
          <h2 className="results-title">Analysis Complete</h2>
          <div style={{ display: 'flex', gap: '8px', marginTop: '8px', flexWrap: 'wrap' }}>
            <span className="results-url-tag" title={meta.canonicalUrl}>
              <Link size={12} />
              {shortUrl}
            </span>
            <span className="results-url-tag">
              {pageTypeInfo.emoji} {pageTypeInfo.label}
            </span>
          </div>
        </div>

        <div className="results-actions">
          <button
            id="reset-btn"
            className="btn-secondary"
            onClick={onReset}
            aria-label="Analyze another URL"
          >
            <RefreshCw size={14} />
            New Analysis
          </button>
          <button
            id="download-html-btn"
            className="btn-secondary"
            onClick={handleDownloadHTML}
            aria-label="Download schemas as HTML script tags"
          >
            <Download size={14} />
            Download HTML
          </button>
          <button
            id="download-json-btn"
            className="btn-primary"
            onClick={handleDownloadAll}
            aria-label="Download all schemas as JSON"
          >
            <Download size={14} />
            Download JSON
          </button>
        </div>
      </div>

      {/* AEO Score */}
      <AEOScoreCard score={score} />

      <div className="section-divider" />

      {/* Schema Cards */}
      <div className="schemas-section">
        <div className="schemas-header">
          <h3 className="schemas-title">
            Generated Schemas
            <span className="schemas-count-badge">{schemas.length}</span>
          </h3>
        </div>

        {schemas.map((schema, i) => (
          <SchemaCard
            key={schema.type}
            schemaResult={schema}
            index={i}
          />
        ))}
      </div>

      {/* Tips */}
      {score.percentage < 60 && (
        <div style={{
          marginTop: '32px',
          padding: '20px 24px',
          background: 'rgba(245,158,11,0.06)',
          border: '1px solid rgba(245,158,11,0.2)',
          borderRadius: '12px',
        }}>
          <h4 style={{ color: '#f59e0b', marginBottom: '12px', fontSize: '14px', fontWeight: 700 }}>
            💡 Quick Wins to Improve Your AEO Score
          </h4>
          <ul style={{ color: '#94a3b8', fontSize: '13px', lineHeight: '1.8', paddingLeft: '16px' }}>
            {score.metrics.filter(m => m.status === 'fail').map(m => (
              <li key={m.id}><strong style={{ color: '#e2e8f0' }}>{m.name}</strong> — {m.detail}</li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );
}
